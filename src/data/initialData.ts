        // 2. Fièvre Typhoïde (SAN-XXXXXX)
        const typhoidRisk = area.floodRiskLevel === 'TRES_ELEVE' ? 2.1 : 1.1;
        const typhoidCases = Math.round(popBase * 5 * mult * typhoidRisk + (Math.cos(month) * 3));
        const typhoidHosp = Math.round(typhoidCases * 0.28);
        const typhoidDeaths = Math.max(0, Math.round(typhoidHosp * 0.06));

        const typhoidId = `SAN-${String(recordCounter++).padStart(6, '0')}`;
